/**
 * **A HIGH-RESOLUTION COORDINATE→ZONE PATCH FOR ISRAEL AND ITS NEIGHBOURS**,
 * derived at build time from the authoritative polygons.
 *
 * ## Why it exists
 *
 * `src/lib/vendor/tz-lookup.js` is a packed raster and it is right for 53 of
 * the 54 shipped cities — but it has no resolution in the Gulf of Aqaba corner,
 * where it hands **`Asia/Amman` to everything below about latitude 30**. That
 * includes Eilat, Yotvata, Ketura, Samar and Ovda, and it includes **Taba,
 * which is Egypt**. Jordan abolished daylight saving in 2022 and Israel did
 * not, so through the Israeli winter the two are an hour apart:
 *
 *     Eilat, Friday 2026-01-16, as resolved → candle 17:44, sunset 18:04
 *     Eilat, same day, correct zone         → candle 16:44, sunset 17:04
 *
 * The app told somebody in Eilat to light at 17:44. Their phone, set to
 * Israel, reads 17:44 when that day's sunset was 17:04 — **forty minutes
 * earlier**. An hour late in the unsafe direction, on a deadline that cannot be
 * moved.
 *
 * ## Why a derived patch and not a hand-drawn border
 *
 * **No border here is drawn by hand**, which matters six kilometres from Aqaba: **every boundary here comes
 * from `geo-tz`, whose polygons are Evan Siroky's timezone-boundary-builder
 * built from OpenStreetMap** — the same lineage as the vendored raster, at full
 * resolution. Spot-checked before it was adopted: geo-tz puts Eilat in
 * `Asia/Jerusalem`, Aqaba in `Asia/Amman` and Taba in `Africa/Cairo`, all
 * correct, where the raster gives Amman for all three.
 *
 * geo-tz itself is **73 MB unpacked** and cannot ship. So it stays a
 * devDependency and this script bakes a small window of it into the bundle.
 *
 * ## The window, and why it is only Israel
 *
 * lat 29.0–33.5, lon 34.0–36.0, at **0.0025°** — cells of about 275 metres, so
 * a border is placed to within ~140 m. That is finer than a phone's own fix.
 * The whole window packs to about 28 KB.
 *
 * **It is bounded to this region on evidence, not on convenience.** A sweep drove
 * eighteen narrow salients elsewhere — Gibraltar, Ceuta, Vaduz, Kaliningrad and
 * the rest — and the raster resolved **18 of 18** correctly. The failure is
 * specific to this corner, and a global patch at this resolution would not fit
 * in a bundle this size.
 *
 * ## Licence
 *
 * The data is **ODbL**, from OpenStreetMap by way of timezone-boundary-builder
 * — the same licence and the same source as the raster this patches, on which
 * it ships WITH ATTRIBUTION: «© OpenStreetMap contributors, ODbL».
 */
import { writeFileSync } from 'node:fs';
import { find } from 'geo-tz';

const LAT0 = 29.0, LAT1 = 33.5, LON0 = 34.0, LON1 = 36.0, STEP = 0.0025;
const rows = Math.round((LAT1 - LAT0) / STEP);
const cols = Math.round((LON1 - LON0) / STEP);

const zones = [];
const index = new Map();
const idOf = (z) => {
  if (!index.has(z)) { index.set(z, zones.length); zones.push(z); }
  return index.get(z);
};

const packedRows = [];
for (let r = 0; r < rows; r++) {
  const lat = LAT0 + (r + 0.5) * STEP;
  let cur = -1, len = 0;
  const runs = [];
  for (let c = 0; c < cols; c++) {
    const lon = LON0 + (c + 0.5) * STEP;
    const v = idOf(find(lat, lon)[0] ?? '');
    if (v === cur) len += 1;
    else { if (len) runs.push(cur.toString(36) + '.' + len.toString(36)); cur = v; len = 1; }
  }
  if (len) runs.push(cur.toString(36) + '.' + len.toString(36));
  packedRows.push(runs.join(','));
}

const packed = packedRows.join(';');
const out = `/**
 * GENERATED by \`scripts/gen-tz-patch.mjs\` — do not edit.
 *
 * A high-resolution coordinate→timezone patch for Israel and its neighbours,
 * derived from geo-tz (timezone-boundary-builder / OpenStreetMap, **ODbL**).
 * Read the generator's header for why it exists and why it is bounded here.
 */
export const TZ_PATCH = {
  lat0: ${LAT0}, lat1: ${LAT1}, lon0: ${LON0}, lon1: ${LON1}, step: ${STEP},
  rows: ${rows}, cols: ${cols},
  zones: ${JSON.stringify(zones)},
  packed: ${JSON.stringify(packed)},
};

let decoded: number[][] | null = null;

/**
 * The zone at a point, or \`null\` when it is outside the patched window — in
 * which case the caller falls back to the vendored raster, which is right
 * everywhere the round measured except this corner.
 */
export function tzPatchAt(lat: number, lon: number): string | null {
  const p = TZ_PATCH;
  if (lat < p.lat0 || lat >= p.lat1 || lon < p.lon0 || lon >= p.lon1) return null;
  if (!decoded) {
    decoded = p.packed.split(';').map((row) => {
      const out: number[] = [];
      for (const run of row.split(',')) {
        const [v, n] = run.split('.');
        const zone = parseInt(v, 36);
        const len = parseInt(n, 36);
        for (let i = 0; i < len; i++) out.push(zone);
      }
      return out;
    });
  }
  const r = Math.floor((lat - p.lat0) / p.step);
  const c = Math.floor((lon - p.lon0) / p.step);
  const row = decoded[r];
  if (!row) return null;
  const z = p.zones[row[c]];
  return z || null;
}
`;
writeFileSync('src/lib/tz-patch.ts', out);
const runs = packedRows.reduce((a, r) => a + r.split(',').length, 0);
console.log(`grid ${rows}x${cols} at ${STEP}°  ·  ${zones.length} zones  ·  ${runs} runs`);
console.log(`src/lib/tz-patch.ts written, packed table ${packed.length} bytes`);
